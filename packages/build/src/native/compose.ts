/**
 * Kotlin for Jetpack Compose (TICKET-013, spec native-outputs): `compose/DesignTokens.kt` with
 * `object DesignTokens` (the shared tokens), `interface BrandTheme` and one `object` per brand.
 */
import type { Diagnostic } from '@dta/core'
import { argb } from './android-xml.js'
import {
  chainText,
  flat,
  grouped,
  identifier,
  number,
  upperCamel,
  words,
  type Named,
} from './names.js'
import type { NativeTokens, NativeValue } from './tokens.js'

const OUTPUT = 'android-compose'

// Kotlin hard keywords: names only with backticks.
const KEYWORDS = new Set(
  'as break class continue do else false for fun if in interface is null object package return super this throw true try typealias typeof val var when while'.split(
    ' ',
  ),
)
const name = (parts: string[]) => {
  const text = identifier(upperCamel(words(parts)))
  return KEYWORDS.has(text) ? `\`${text}\`` : text
}

const kotlinString = (text: string) =>
  `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/\n/g, '\\n')}"`

/** A Kotlin package name: dot-separated identifiers. */
export const isPackageName = (text: string) =>
  /^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$/.test(text)

// Types are written in full (`androidx.compose.ui.graphics.Color`): a token group named `Color`
// or `String` becomes an object of that name, which would hide the platform type.
const COLOR = 'androidx.compose.ui.graphics.Color'
const isInt = (value: number) => Number.isInteger(value) && Math.abs(value) <= 2_147_483_647
/** A Kotlin Double literal: always with a decimal point (`2.0`, not `2`). */
const double = (value: number) => {
  const text = number(value)
  return /[.]/.test(text) ? text : `${text}.0`
}
/** `16`, `1.5` before `.dp`: whole numbers stay Int receivers, others Double. */
const decimal = (value: number) => (isInt(value) ? String(value) : double(value))

/** The value as Kotlin writes it; `asDouble` makes a whole number a Double (a brand member). */
function kotlin(value: NativeValue, asDouble = false): { type: string; code: string } {
  if (asDouble && value.kind === 'number')
    return { type: 'kotlin.Double', code: double(value.value) }
  switch (value.kind) {
    case 'color':
      return { type: COLOR, code: `${COLOR}(0x${argb(value.color).slice(1)})` }
    case 'length':
      return { type: 'androidx.compose.ui.unit.Dp', code: `${decimal(value.value)}.dp` }
    case 'font-size':
      return { type: 'androidx.compose.ui.unit.TextUnit', code: `${decimal(value.value)}.sp` }
    case 'number':
      return isInt(value.value)
        ? { type: 'kotlin.Int', code: String(value.value) }
        : { type: 'kotlin.Double', code: double(value.value) }
    case 'string':
      return { type: 'kotlin.String', code: kotlinString(value.value) }
    case 'boolean':
      return { type: 'kotlin.Boolean', code: String(value.value) }
    case 'duration':
      return { type: 'kotlin.Long', code: `${Math.round(value.value)}L` }
  }
}

const doc = (named: Named, indent: string) =>
  `${indent}/** ${chainText(named.token).replace(/\*\//g, '* /').replace(/\/\*/g, '/ *').replace(/\n/g, ' ')} */`

function constant(named: Named, indent: string, keyword: string, asDouble = false): string[] {
  const { type, code } = kotlin(named.token.value, asDouble)
  return [doc(named, indent), `${indent}${keyword} ${named.name}: ${type} = ${code}`]
}

export function composeFiles(
  tokens: NativeTokens,
  outDir: string,
  packageName: string,
  diagnostics: Diagnostic[],
): Array<{ path: string; content: string }> {
  const groups = grouped(tokens.shared, name, (first) => name([first]), OUTPUT, diagnostics)
  // A token without a group next to a group object of the same name: `DesignTokens.Colors`
  // would be both. The object wins; the token is left out.
  const objects = new Set(groups.map((entry) => entry.group).filter((group) => group !== ''))
  for (const entry of groups.filter((g) => g.group === '')) {
    entry.tokens = entry.tokens.filter((named) => {
      if (!objects.has(named.name)) return true
      diagnostics.push({
        severity: 'warning',
        code: 'native-name-collision',
        message: `${OUTPUT}: the token "${named.token.path.join('.')}" and the group "${named.name}" both become "DesignTokens.${named.name}"; the token is left out. Rename one of them.`,
      })
      return false
    })
  }
  const brandTokens = tokens.brands[0]?.tokens ?? []
  if (groups.length === 0 && brandTokens.length === 0) return []
  const lines = [
    '// Generated by dta build; do not edit.',
    `package ${packageName}`,
    '',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.sp',
    '',
    'object DesignTokens {',
  ]
  groups.forEach(({ group, tokens: named }, i) => {
    if (i > 0) lines.push('')
    if (group === '') {
      for (const token of named) lines.push(...constant(token, '    ', 'val'))
      return
    }
    lines.push(`    object ${group} {`)
    for (const token of named) lines.push(...constant(token, '        ', 'val'))
    lines.push('    }')
  })
  lines.push('}')

  if (brandTokens.length > 0) {
    const members = flat(brandTokens, name, OUTPUT, diagnostics)
    const kept = new Set(members.map((member) => member.token.path.join('/')))
    // One type per member in every brand: a number that is fractional in one brand is a Double
    // in all of them (`4` in one and `4.5` in another would not compile as Int and Double).
    const fractional = new Set(
      tokens.brands.flatMap((brand) =>
        brand.tokens
          .filter((token) => token.value.kind === 'number' && !isInt(token.value.value))
          .map((token) => token.path.join('/')),
      ),
    )
    const asDouble = (named: Named) => fractional.has(named.token.path.join('/'))
    lines.push(
      '',
      '/** The brand tokens (read through a brand collection): one object per brand, for a CompositionLocal. */',
      'interface BrandTheme {',
      ...members.map(
        (member) => `    val ${member.name}: ${kotlin(member.token.value, asDouble(member)).type}`,
      ),
      '}',
    )
    for (const brand of tokens.brands) {
      const own = flat(
        brand.tokens.filter((token) => kept.has(token.path.join('/'))),
        name,
        OUTPUT,
        [],
      )
      lines.push(
        '',
        `/** The ${brand.name} theme. */`,
        `object ${name([brand.name])} : BrandTheme {`,
        ...own.flatMap((member, i) => [
          ...(i > 0 ? [''] : []),
          ...constant(member, '    ', 'override val', asDouble(member)),
        ]),
        '}',
      )
    }
  }
  return [{ path: `${outDir}compose/DesignTokens.kt`, content: `${lines.join('\n')}\n` }]
}
