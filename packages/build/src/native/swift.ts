/**
 * iOS Swift for SwiftUI (TICKET-011, spec native-outputs): `DesignTokens.swift` with the shared
 * tokens and the `BrandTheme` protocol, and `BrandTokens+<Brand>.swift` per brand.
 */
import type { Diagnostic } from '@dta/core'
import {
  chainText,
  flat,
  grouped,
  identifier,
  lowerCamel,
  number,
  upperCamel,
  words,
  type Named,
} from './names.js'
import type { NativeTokens, NativeValue } from './tokens.js'

const OUTPUT = 'ios-swift'
const HEADER = '// Generated by dta build; do not edit.'
// Types are written in full (`SwiftUI.Color`): a token group named `Color` or `String` becomes
// an enum of that name, which would hide the platform type inside `DesignTokens`.
const IMPORTS = ['import CoreGraphics', 'import Foundation', 'import SwiftUI']

// Swift keywords that cannot be names without backticks.
const KEYWORDS = new Set(
  'associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private precedencegroup protocol public rethrows static struct subscript typealias var break case catch continue default defer do else fallthrough for guard if in repeat return throw switch where while as Any false is nil self Self super throws true try Type Protocol'.split(
    ' ',
  ),
)

const property = (parts: string[]) => {
  const name = identifier(lowerCamel(words(parts)))
  return KEYWORDS.has(name) ? `\`${name}\`` : name
}
const typeName = (parts: string[]) => {
  const name = identifier(upperCamel(words(parts)))
  return KEYWORDS.has(name) ? `\`${name}\`` : name
}

const swiftString = (text: string) =>
  `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`

/** The Swift type and the expression of a value. */
function swift(value: NativeValue): { type: string; code: string } {
  switch (value.kind) {
    case 'color': {
      const { r, g, b, a = 1 } = value.color
      return {
        type: 'SwiftUI.Color',
        code: `SwiftUI.Color(.sRGB, red: ${number(r)}, green: ${number(g)}, blue: ${number(b)}, opacity: ${number(a)})`,
      }
    }
    case 'length':
    case 'font-size':
      return { type: 'CoreGraphics.CGFloat', code: number(value.value) }
    case 'number':
      return { type: 'Swift.Double', code: number(value.value) }
    case 'string':
      return { type: 'Swift.String', code: swiftString(value.value) }
    case 'boolean':
      return { type: 'Swift.Bool', code: String(value.value) }
    case 'duration':
      return { type: 'Foundation.TimeInterval', code: number(value.value / 1000) }
  }
}

const doc = (named: Named, indent: string) =>
  `${indent}/// ${chainText(named.token).replace(/\n/g, ' ')}`

function constant(named: Named, indent: string, keyword: string): string[] {
  const { type, code } = swift(named.token.value)
  return [doc(named, indent), `${indent}${keyword} ${named.name}: ${type} = ${code}`]
}

export function swiftFiles(
  tokens: NativeTokens,
  outDir: string,
  diagnostics: Diagnostic[],
): Array<{ path: string; content: string }> {
  const groups = grouped(tokens.shared, property, (first) => typeName([first]), OUTPUT, diagnostics)
  const lines = [HEADER, ...IMPORTS, '', 'public enum DesignTokens {']
  groups.forEach(({ group, tokens: named }, i) => {
    if (i > 0) lines.push('')
    if (group === '') {
      for (const token of named) lines.push(...constant(token, '    ', 'public static let'))
      return
    }
    lines.push(`    public enum ${group} {`)
    for (const token of named) lines.push(...constant(token, '        ', 'public static let'))
    lines.push('    }')
  })
  lines.push('}')

  const files = []
  const brandTokens = tokens.brands[0]?.tokens ?? []
  if (brandTokens.length > 0) {
    const members = flat(brandTokens, (path) => property(path), OUTPUT, diagnostics)
    const kept = new Set(members.map((member) => member.token.path.join('/')))
    lines.push(
      '',
      '/// The brand tokens (read through a brand collection). `BrandTokens+<Brand>.swift` has one',
      '/// theme per brand:',
      '/// `let theme: BrandTheme = BrandA()`.',
      'public protocol BrandTheme {',
      ...members.map(
        (member) => `    var ${member.name}: ${swift(member.token.value).type} { get }`,
      ),
      '}',
    )
    for (const brand of tokens.brands) {
      const name = typeName([brand.name])
      const own = flat(
        brand.tokens.filter((token) => kept.has(token.path.join('/'))),
        (path) => property(path),
        OUTPUT,
        [],
      )
      const body = [
        HEADER,
        ...IMPORTS,
        '',
        `/// The ${brand.name} theme: the brand tokens in ${brand.name}.`,
        `public struct ${name}: BrandTheme {`,
        '    public init() {}',
        '',
        ...own.flatMap((member, i) => [
          ...(i > 0 ? [''] : []),
          ...constant(member, '    ', 'public let'),
        ]),
        '}',
        '',
      ]
      files.push({ path: `${outDir}BrandTokens+${name}.swift`, content: body.join('\n') })
    }
  }
  if (groups.length > 0 || brandTokens.length > 0) {
    files.unshift({ path: `${outDir}DesignTokens.swift`, content: `${lines.join('\n')}\n` })
  }
  return files
}
