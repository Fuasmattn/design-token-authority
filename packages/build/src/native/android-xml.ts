/**
 * Android resource XML (TICKET-012, spec native-outputs): `main/values/colors.xml` and
 * `dimens.xml` with the shared tokens, `<brand>/values/` with the brand tokens (product-flavour
 * source sets). Colours and dimensions only.
 */
import { toHex, type Color, type Diagnostic } from '@dta/core'
import { chainText, flat, identifier, number, snake, words } from './names.js'
import type { NativeToken } from './tokens.js'
import type { NativeTokens } from './tokens.js'

const OUTPUT = 'android-xml'

/** `#AARRGGBB`, upper case, as Android writes it. */
export function argb(color: Color): string {
  const hex = toHex({ ...color, a: color.a ?? 1 }).slice(1)
  const rgb = hex.slice(0, 6)
  const alpha = hex.length === 8 ? hex.slice(6) : 'ff'
  return `#${alpha}${rgb}`.toUpperCase()
}

/** Resource names: lower case letters, digits and `_`, starting with a letter. */
const resourceName = (path: string[]) => {
  const name = snake(words(path, true))
  return name === '' || /^[a-z]/.test(name) ? name : `t${identifier(name)}`
}

/** XML comments may not contain `--` nor end in `-`. */
const escapeComment = (text: string) => {
  let safe = text
  while (safe.includes('--')) safe = safe.replace(/--/g, '- -')
  return safe.endsWith('-') ? `${safe} ` : safe
}

/** A brand's folder: a product-flavour name (lower case letters, digits, `_`). */
export const flavour = (brand: string) => snake(words([brand], true)) || 'brand'

function resources(entries: string[]): string {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by dta build; do not edit. -->',
    '<resources>',
    ...entries,
    '</resources>',
    '',
  ].join('\n')
}

function files(tokens: readonly NativeToken[], dir: string, diagnostics: Diagnostic[]) {
  const named = flat(
    tokens.filter((token) => ['color', 'length', 'font-size'].includes(token.value.kind)),
    resourceName,
    OUTPUT,
    diagnostics,
  )
  const colors: string[] = []
  const dimens: string[] = []
  for (const { name, token } of named) {
    const comment = `    <!-- ${escapeComment(chainText(token))} -->`
    const value = token.value
    if (value.kind === 'color') {
      colors.push(comment, `    <color name="${name}">${argb(value.color)}</color>`)
    } else if (value.kind === 'length' || value.kind === 'font-size') {
      const unit = value.kind === 'font-size' ? 'sp' : 'dp'
      dimens.push(comment, `    <dimen name="${name}">${number(value.value)}${unit}</dimen>`)
    }
  }
  return [
    ...(colors.length > 0 ? [{ path: `${dir}colors.xml`, content: resources(colors) }] : []),
    ...(dimens.length > 0 ? [{ path: `${dir}dimens.xml`, content: resources(dimens) }] : []),
  ]
}

export function androidXmlFiles(
  tokens: NativeTokens,
  outDir: string,
  diagnostics: Diagnostic[],
): Array<{ path: string; content: string }> {
  // Resource XML holds colours and dimensions here; the other kinds are in Swift and Compose.
  const other = [...tokens.shared, ...(tokens.brands[0]?.tokens ?? [])].filter(
    (token) => !['color', 'length', 'font-size'].includes(token.value.kind),
  ).length
  if (other > 0) {
    diagnostics.push({
      severity: 'warning',
      code: 'native-xml-kinds',
      message: `${OUTPUT}: ${other} token${other === 1 ? ' is' : 's are'} not a colour or a dimension (numbers, strings, booleans, durations) and ${other === 1 ? 'is' : 'are'} not written; android-compose and ios-swift have ${other === 1 ? 'it' : 'them'}.`,
    })
  }
  return [
    ...files(tokens.shared, `${outDir}main/values/`, diagnostics),
    ...tokens.brands.flatMap((brand, i) =>
      // Collisions are reported once, for the first brand.
      files(brand.tokens, `${outDir}${flavour(brand.name)}/values/`, i === 0 ? diagnostics : []),
    ),
  ]
}
