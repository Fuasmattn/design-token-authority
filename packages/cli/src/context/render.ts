const BEGIN = '<!-- dta:begin -->'
const END = '<!-- dta:end -->'

/** The block DTA owns in `AGENTS.md`: a pointer to the context file and the skill. */
export function agentsBlock(designPath: string): string {
  return [
    BEGIN,
    `<!-- ${CONTEXT_MARKER}. DTA keeps this block up to date; the rest of the file is yours. -->`,
    '',
    '## Design tokens',
    '',
    `Before you write a colour, size or font in code, read [${designPath}](${designPath}): the tokens to use and the rules. Look up a value with \`dta token find '<value>'\`. The DTA skill (\`dta skill add\`) has the workflow for changing tokens.`,
    END,
  ].join('\n')
}

/**
 * `AGENTS.md` with the DTA block added or replaced. Everything outside the block stays byte for
 * byte; a missing file becomes just the block.
 */
export function updateAgentsMd(existing: string | null, designPath: string): string {
  const block = agentsBlock(designPath)
  if (existing === null || existing === '') return `${block}\n`
  const start = existing.indexOf(BEGIN)
  const end = existing.indexOf(END, start)
  if (start !== -1 && end !== -1) {
    return existing.slice(0, start) + block + existing.slice(end + END.length)
  }
  const separator = existing.endsWith('\n\n') ? '' : existing.endsWith('\n') ? '\n' : '\n\n'
  return `${existing}${separator}${block}\n`
}
