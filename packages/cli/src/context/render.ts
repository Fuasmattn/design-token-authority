/**
 * `DESIGN.md`: a compact description of this project's tokens for coding agents, generated from
 * the token model and the config. Primitives are never listed (code should not use them); the
 * tokens to use are listed in full when they fit the size budget, otherwise by group.
 */
import { analyzeStructure, describeToken, nameToDot, type TokenModel, formatValue } from '@dta/core'
import { codeNames, isBuilt } from '../code-names.js'
import type { Config } from '../config/schema.js'

/** Marks a file or block as written by `dta context`. */
export const CONTEXT_MARKER = 'Generated by `dta context`'

/** About 2,000 tokens of text, at roughly four characters per token. */
export const DEFAULT_BUDGET_CHARS = 8000

export interface RenderOptions {
  version: string
  budgetChars?: number
}

interface Row {
  name: string
  collection: string
  css: string
  tailwind?: string
  value: string
}

const code = (text: string) => `\`${text.replace(/`/g, "'")}\``
const cell = (text: string) => text.replace(/\|/g, '\\|')

function rowsOf(model: TokenModel, config: Config | null, collections: Set<string>): Row[] {
  const rows: Row[] = []
  for (const collection of model.collections) {
    if (!collections.has(collection.name)) continue
    for (const token of collection.tokens) {
      const name = nameToDot(token.name)
      const description = describeToken(model, name)
      const names = description && codeNames(model, config, description, token.extensions)
      if (!description || !names) continue
      const readings = description.readings.map((reading) => ({
        value: reading.value === undefined ? '?' : formatValue(reading.value),
        modes: Object.values(reading.modes).join(' · '),
      }))
      // The same value in every mode is shown once.
      const same = readings.every((reading) => reading.value === readings[0]?.value)
      const values = same
        ? [readings[0]?.value ?? '?']
        : readings.map((reading) =>
            reading.modes ? `${reading.modes} ${reading.value}` : reading.value,
          )
      rows.push({
        name,
        collection: collection.name,
        css: names.css,
        ...(names.tailwind ? { tailwind: names.tailwind } : {}),
        value: values.join(', '),
      })
    }
  }
  return rows.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
}

function tokenTable(rows: readonly Row[]): string {
  const tailwind = rows.some((row) => row.tailwind)
  const header = tailwind
    ? '| Token | CSS | Tailwind | Value |\n| --- | --- | --- | --- |'
    : '| Token | CSS | Value |\n| --- | --- | --- |'
  const lines = rows.map((row) =>
    tailwind
      ? `| ${cell(row.name)} | ${code(`var(${row.css})`)} | ${row.tailwind ? code(row.tailwind) : ''} | ${cell(row.value)} |`
      : `| ${cell(row.name)} | ${code(`var(${row.css})`)} | ${cell(row.value)} |`,
  )
  return [header, ...lines].join('\n')
}

/** Groups by the first two name segments, with counts and a query to list each group. */
function groupTable(rows: readonly Row[]): string {
  const groups = new Map<string, Row[]>()
  for (const row of rows) {
    const key = row.name.split('.').slice(0, 2).join('.')
    groups.set(key, [...(groups.get(key) ?? []), row])
  }
  const lines = [...groups].map(([group, members]) => {
    const examples = members
      .slice(0, 3)
      .map((row) => code(row.name.slice(group.length + 1) || row.name))
      .join(', ')
    return `| ${cell(group)} | ${members.length} | ${examples}${members.length > 3 ? ', …' : ''} | ${code(`dta token list --match '${group}.**'`)} |`
  })
  return [
    '| Group | Tokens | For example | List them |',
    '| --- | --- | --- | --- |',
    ...lines,
  ].join('\n')
}

function rules(config: Config | null): string[] {
  const lines: string[] = []
  const lint = config?.lint?.rules
  const alias = lint?.['semantic-must-alias']
  if (alias && alias.severity !== 'off' && alias.collections?.length) {
    lines.push(
      `- Tokens in ${alias.collections.map(code).join(', ')} are aliases only: point them at another token, never a raw value.`,
    )
  }
  const naming = lint?.['naming-pattern']
  if (naming && naming.severity !== 'off' && naming.patterns) {
    for (const [collection, pattern] of Object.entries(naming.patterns)) {
      lines.push(`- Every name segment in ${code(collection)} matches ${code(pattern)}.`)
    }
  }
  const contrast = lint?.['color-contrast']
  if (contrast && contrast.severity !== 'off' && contrast.pairs?.length) {
    const ratio = contrast.minRatio ?? 4.5
    lines.push(`- Text and background pairs keep a contrast of at least ${ratio}:1:`)
    for (const [foreground, background] of contrast.pairs) {
      lines.push(`  - ${code(foreground)} on ${code(background)}`)
    }
  }
  return lines
}

export function renderDesignMd(
  model: TokenModel,
  config: Config | null,
  options: RenderOptions,
): string {
  const structure = analyzeStructure(model)
  const tokensDir = config?.tokens.dir ?? 'tokens'
  const cssDir = config?.outputs?.css?.outDir ?? 'output/css'
  const brands = config?.brands ?? []
  const primitives = new Set(
    structure.collections
      .filter((collection) => collection.inferredRole === 'primitives')
      .map((collection) => collection.name),
  )
  const listed = new Set(
    model.collections
      .map((collection) => collection.name)
      .filter((name) => !primitives.has(name) && isBuilt(model, name, config)),
  )

  const out: string[] = [
    `<!-- ${CONTEXT_MARKER} (DTA ${options.version}). Do not edit: run \`dta context\` again to update it. -->`,
    '',
    '# Design tokens',
    '',
    `The design tokens of this project live in ${code(`${tokensDir}/`)} (DTCG JSON, managed with DTA); \`dta build\` writes them to CSS custom properties${config?.outputs?.tailwind ? ' and Tailwind theme files' : ''}. In code, use the tokens below instead of raw colours, sizes or fonts.`,
    '',
    "Do not invent token names. To find the token for a value, run `dta token find '<value>'`; to check one, `dta token get <name>`.",
    '',
  ]

  if (brands.length > 0) {
    out.push(
      '## Brands and themes',
      '',
      `Built: ${brands.map(code).join(', ')}. Load ${code(`${cssDir}/variables.css`)} and the theme files ${code(`${cssDir}/themes/<brand>.css`)}, then switch with the attribute on any element:`,
      '',
      '```html',
      `<html data-brand="${brands[0].toLowerCase()}">`,
      '```',
      '',
      `Attribute values: ${brands.map((brand) => code(brand.toLowerCase())).join(', ')}.`,
      '',
    )
  }

  out.push(
    '## Collections',
    '',
    '| Collection | Modes | Tokens | Use in code |',
    '| --- | --- | --- | --- |',
  )
  for (const collection of structure.collections) {
    const use = primitives.has(collection.name)
      ? 'no: primitives, reached through aliases'
      : listed.has(collection.name)
        ? 'yes'
        : 'not in the build output'
    out.push(
      `| ${cell(collection.name)} | ${cell(collection.modeNames.join(', '))} | ${collection.variableCount} | ${use} |`,
    )
  }
  out.push('')

  const rows = rowsOf(model, config, listed)
  if (rows.length > 0) {
    const full = tokenTable(rows)
    const budget = options.budgetChars ?? DEFAULT_BUDGET_CHARS
    const used = out.join('\n').length
    out.push('## Tokens to use', '')
    if (used + full.length <= budget) {
      out.push(full)
    } else {
      out.push(
        `${rows.length} tokens, too many to list here. By group (\`dta token get <name>\` shows one, with its CSS and Tailwind names):`,
        '',
        groupTable(rows),
      )
    }
    out.push('')
  }

  const ruleLines = rules(config)
  out.push('## Rules', '')
  out.push(
    '- In components, use the tokens above (semantic tokens), never primitives or raw values.',
    '- Do not edit the build output or this file; change the token files and run `dta lint`, `dta build` and `dta diff --tokens-only`.',
    ...ruleLines,
    '',
  )
  return out.join('\n')
}

