/**
 * The DTA skill for coding agents (Agent Skills format: `SKILL.md` with `name` and
 * `description` front matter). Project-independent: the project's own tokens are in the context
 * file (`dta context`). The command list comes from the command registry, so the skill cannot
 * name a command that does not exist; a test checks every `dta …` line against the CLI.
 */
import { commandReference } from '../commands.js'

/** Marks a file as written by `dta skill add`; only such a file is overwritten. */
export const SKILL_MARKER = 'Generated by `dta skill add`'

export function renderSkill(version: string): string {
  const commands = commandReference()
    .map((command) => `- \`dta ${command.name}\`: ${command.description}.`)
    .join('\n')
  return `---
name: dta
description: Design tokens in a project that uses DTA (Design Token Authority). Use when writing or changing UI styles (look up a token instead of writing a colour, size or font), when changing token files (lint, build and diff the change), or when reviewing token changes.
---

<!-- ${SKILL_MARKER} (DTA ${version}). Do not edit: run \`dta skill add\` again to update it. -->

# DTA: design tokens

This project keeps its design tokens in DTCG JSON files, one file per collection and mode (\`{Collection}.{Mode}.json\`), in the folder \`tokens.dir\` of \`dta.config.ts\` (usually \`tokens/\`). Aliases look like \`{Colors.Brand.Primary}\`. \`dta build\` writes CSS custom properties, Tailwind theme files and JavaScript from them; brands and themes switch with \`data-brand\` on an element. Figma is synced with \`dta pull\` and \`dta push\`.

If \`DESIGN.md\` exists at the project root, read it first: it lists this project's brands, collections and the semantic tokens to use (\`dta context\` writes it).

## Before you write a value in code

1. Find the token for the value: \`dta token find '#2f55d4'\` (colours as hex or \`rgb(…)\`, numbers such as \`16\`). Add \`--near\` for colours that are only close. Use the first line it prints: tokens the build writes come first, semantic tokens before primitives.
2. Check a token before you use it: \`dta token get Colors.Brand.Primary\` shows its value per brand or mode, its alias chain, and the CSS custom property and Tailwind name to write.
3. Browse: \`dta token list --match 'Colors.**'\`. Every query takes \`--format json\`.
4. After writing styles, run \`dta audit src\` (or the files you changed): it lists hard-coded values that equal a token and names the token to use. Exit code 1 means it found some; fix them, or mark a deliberate one with a \`dta-audit-ignore\` comment on its line.

Rules:

- In components, use semantic tokens through their CSS custom property (\`var(--…)\`) or Tailwind name, never a raw hex, px or font value, and not a primitive when a semantic token fits.
- Do not invent token names. When no token fits, say so and ask; do not add a token without being asked.

## When you change token files

Work in a loop until it is clean:

1. Edit the token files (never the build output).
2. \`dta lint\`: exit code 2 means lint errors; fix them. Warnings are allowed but worth reading.
3. \`dta build\`.
4. \`dta diff --tokens-only --format markdown\`: which tokens changed and what depends on them. With stories configured, \`dta diff\` also compares screenshots and names the tokens behind each visual change.
5. Read the result, fix, repeat.

## Never

- Run \`dta push --yes\`, or \`dta push\` without being asked: a person pushes to Figma. \`dta push --dry-run\` shows the plan and changes nothing.
- Run \`dta pull\` or \`dta clean\` without being asked: they overwrite or remove token files.
- Edit generated files: the build output, \`DESIGN.md\`, this skill.

## Exit codes

- 0: success (also with lint warnings).
- 1: failed, or nothing found: \`dta token get\` with an unknown name (it prints the closest names), \`dta token find\` without a match.
- 2: invalid input: the config, credentials, a bad option value, or lint errors.

## Commands

${commands}

\`dta <command> --help\` shows every option.
`
}
