// Commands

async function helpOf(args: string[]): Promise<string> {
  let out = ''
  await runCli([...args, '--help'], { stdout: (text) => void (out += text), stderr: () => {} })
  return out.trimEnd()
}

export async function commandsPage(): Promise<string> {
  const sections: string[] = []
  for (const command of commandReference()) {
    sections.push(
      `## dta ${command.name}\n\n${command.description}.\n\n\`\`\`text\n$ dta ${command.name} --help\n${await helpOf(command.name.split(' '))}\n\`\`\``,
    )
  }
  return `---
title: Commands
description: Every dta command and option, from the CLI's own help.
sidebar:
  order: 1
---

${GENERATED_NOTE}

The help text of every command, as \`dta <command> --help\` prints it. Exit codes: [Exit codes](/reference/exit-codes/).

\`\`\`text
$ dta --help
${await helpOf([])}
\`\`\`

${sections.join('\n\n')}
`
}

