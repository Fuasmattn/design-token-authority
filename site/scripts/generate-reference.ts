type Schema = Record<string, unknown>

const asSchema = (value: unknown): Schema =>
  typeof value === 'object' && value !== null ? (value as Schema) : {}

/** A short TypeScript-like type for a JSON Schema node. */
export function typeOf(node: Schema): string {
  if (node.not !== undefined) return 'never'
  if (node.const !== undefined) return JSON.stringify(node.const).replaceAll('"', "'")
  if (Array.isArray(node.enum)) {
    return node.enum.map((value) => JSON.stringify(value).replaceAll('"', "'")).join(' | ')
  }
  for (const list of ['anyOf', 'oneOf'] as const) {
    const options = node[list]
    if (Array.isArray(options)) {
      const types = options.map((option: unknown) => typeOf(asSchema(option)))
      return [...new Set(types)].join(' | ')
    }
  }
  if (node.type === 'array') {
    if (Array.isArray(node.prefixItems)) {
      return `[${node.prefixItems.map((item) => typeOf(asSchema(item))).join(', ')}]`
    }
    const item = typeOf(asSchema(node.items))
    return item.includes(' ') ? `(${item})[]` : `${item}[]`
  }
  if (node.type === 'object') {
    const values = node.additionalProperties
    if (typeof values === 'object' && values !== null && node.properties === undefined) {
      return `{ [name]: ${typeOf(asSchema(values))} }`
    }
    return 'object'
  }
  return typeof node.type === 'string' ? node.type : 'any'
}

const cell = (text: string) => text.replaceAll('|', '\\|').replaceAll('\n', ' ')

/** Markdown text for a cell: `<` outside code spans would be read as HTML. */
const prose = (text: string) =>
  cell(text)
    .split('`')
    .map((part, i) => (i % 2 === 0 ? part.replaceAll('<', '&lt;') : part))
    .join('`')

interface Row {
  key: string
  type: string
  default: string
  description: string
}

/** One row per key, depth first; objects get a row and then their properties. */
export function configRows(schema: Schema): Row[] {
  const rows: Row[] = []
  const visit = (properties: Schema, required: unknown, prefix: string, note: string) => {
    for (const [key, value] of Object.entries(properties)) {
      const node = asSchema(value)
      const name = prefix ? `${prefix}.${key}` : key
      const isRequired = Array.isArray(required) && required.includes(key)
      const description = typeof node.description === 'string' ? node.description : ''
      rows.push({
        key: name,
        type: typeOf(node) + (isRequired ? ' (required)' : ''),
        default: node.default === undefined ? '' : JSON.stringify(node.default),
        description: note ? `${note} ${description}` : description,
      })
      if (node.properties) visit(asSchema(node.properties), node.required, name, '')
      for (const list of ['anyOf', 'oneOf'] as const) {
        for (const option of (node[list] ?? []) as unknown[]) {
          const variant = asSchema(option)
          if (!variant.properties) continue
          const tag = asSchema(asSchema(variant.properties).type).const
          const properties = Object.fromEntries(
            Object.entries(asSchema(variant.properties)).filter(([k]) => k !== 'type'),
          )
          visit(properties, variant.required, name, tag ? `(\`type: '${tag}'\`)` : '')
        }
      }
    }
  }
  visit(asSchema(schema.properties), schema.required, '', '')
  return rows
}

export function configurationPage(): string {
  const schema = configJsonSchema()
  const rows = configRows(schema)
  const sections = Object.keys(asSchema(schema.properties))
  const tables = sections.map((section) => {
    const sectionRows = rows.filter(
      (row) => row.key === section || row.key.startsWith(`${section}.`),
    )
    const body = sectionRows
      .map(
        (row) =>
          `| \`${cell(row.key)}\` | \`${cell(row.type)}\` | ${row.default ? `\`${cell(row.default)}\`` : ''} | ${prose(row.description)} |`,
      )
      .join('\n')
    return `## ${section}\n\n| Key | Type | Default | Description |\n| --- | --- | --- | --- |\n${body}`
  })
  return `---
title: Configuration
description: Every key of dta.config.ts, from the config schema of the CLI.
sidebar:
  order: 2
---

${GENERATED_NOTE}

The project config is \`dta.config.ts\` (also \`.mts\`, \`.js\`, \`.mjs\` or \`.json\`). Unknown keys are rejected. This page is generated from the same schema the CLI validates with; as a JSON Schema it is published at [\`/schemas/dta.config.schema.json\`](/schemas/dta.config.schema.json), so a \`dta.config.json\` can point \`$schema\` at it. Example configs: [Core concepts](/start/concepts/#config).

${tables.join('\n\n')}
`
}

