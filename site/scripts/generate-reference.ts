/** Sections in sidebar order. The design system and playground pages are about the website. */
const LLM_SECTIONS = [
  ['start', 'Start'],
  ['learn', 'Learn'],
  ['guides', 'Guides'],
  ['reference', 'Reference'],
  ['contribute', 'Contribute'],
] as const

export interface DocPage {
  url: string
  title: string
  description: string
  order: number
  body: string
}

function frontmatter(source: string): { data: Record<string, string>; body: string } {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(source)
  if (!match) return { data: {}, body: source }
  const data: Record<string, string> = {}
  for (const line of match[1].split('\n')) {
    const field = /^\s*(title|description|order):\s*(.*)$/.exec(line)
    if (field) data[field[1]] = field[2].replace(/^['"]|['"]$/g, '')
  }
  return { data, body: source.slice(match[0].length) }
}

/** MDX to plain markdown: imports out, `<Code code={raw}>` inlined, other components dropped. */
export function toMarkdown(body: string, file: string): string {
  const raws = new Map<string, string>()
  for (const [, name, spec] of body.matchAll(/^import (\w+) from '([^']+)\?raw'$/gm)) {
    raws.set(name, fs.readFileSync(path.resolve(path.dirname(file), spec), 'utf8').trimEnd())
  }
  return body
    .replace(/^import .*$\n?/gm, '')
    .replace(/\{\/\*[\s\S]*?\*\/\}\n?/g, '')
    .replace(/<!--[\s\S]*?-->\n?/g, '')
    .replace(/<Code\s+([\s\S]*?)\/>/g, (_, attributes: string) => {
      const code = raws.get(/code=\{(\w+)\}/.exec(attributes)?.[1] ?? '') ?? ''
      const lang = /lang="([^"]*)"/.exec(attributes)?.[1] ?? ''
      const title = /title="([^"]*)"/.exec(attributes)?.[1]
      return `\`\`\`${lang}${title ? ` title="${title}"` : ''}\n${code}\n\`\`\``
    })
    .replace(/^\s*<\/?[A-Z][\w.]*[^>]*>\s*$\n?/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

export function docPages(): DocPage[] {
  const pages: DocPage[] = []
  const walk = (dir: string) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name)
      if (entry.isDirectory()) walk(full)
      else if (/\.mdx?$/.test(entry.name)) {
        const { data, body } = frontmatter(fs.readFileSync(full, 'utf8'))
        const slug = path
          .relative(docsDir, full)
          .replace(/\.mdx?$/, '')
          .replace(/(^|\/)index$/, '')
        pages.push({
          url: `/${slug}${slug ? '/' : ''}`,
          title: data.title ?? slug,
          description: data.description ?? '',
          order: data.order === undefined ? 50 : Number(data.order),
          body: toMarkdown(body, full),
        })
      }
    }
  }
  for (const [dir] of LLM_SECTIONS) walk(path.join(docsDir, dir))
  const section = (url: string) => LLM_SECTIONS.findIndex(([dir]) => url.startsWith(`/${dir}/`))
  const depth = (url: string) => url.split('/').length
  return pages.sort(
    (a, b) =>
      section(a.url) - section(b.url) ||
      depth(a.url) - depth(b.url) ||
      a.order - b.order ||
      a.title.localeCompare(b.title),
  )
}

export function llmsTxt(pages: DocPage[]): string {
  const sections = LLM_SECTIONS.map(([dir, label]) => {
    const links = pages
      .filter((page) => page.url.startsWith(`/${dir}/`))
      .map(
        (page) =>
          `- [${page.title}](${SITE_URL}${page.url})${page.description ? `: ${page.description}` : ''}`,
      )
    return `## ${label}\n\n${links.join('\n')}`
  })
  return `# Design Token Authority

> The deterministic backbone for design token workflows, built for humans and agents: a CLI that syncs Figma variables with DTCG token files, lints them, builds CSS, JavaScript and Tailwind outputs, and shows token changes and their visual effect in pull requests.

The full text of every page below is in [/llms-full.txt](${SITE_URL}/llms-full.txt). The config JSON Schema is at [/schemas/dta.config.schema.json](${SITE_URL}/schemas/dta.config.schema.json), the token-file JSON Schema at [/schemas/token-file.schema.json](${SITE_URL}/schemas/token-file.schema.json), the JSON output of \`dta token\` at [/schemas/dta.token.schema.json](${SITE_URL}/schemas/dta.token.schema.json), of \`dta audit\` at [/schemas/dta.audit.schema.json](${SITE_URL}/schemas/dta.audit.schema.json).

${sections.join('\n\n')}
`
}

export function llmsFullTxt(pages: DocPage[]): string {
  return `${pages.map((page) => `# ${page.title}\n\nURL: ${SITE_URL}${page.url}\n\n${page.body}`).join('\n\n---\n\n')}\n`
}

