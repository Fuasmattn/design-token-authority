/**
 * The `dta diff` report is styled with the website's design system (DTA Drafting Table). Its
 * token CSS is built with DTA from site/tokens, like the website's, and committed into
 * @dta/visual-diff as a module (the report must not depend on the site at runtime).
 *
 *   pnpm report:tokens     rewrite packages/visual-diff/src/report/tokens-css.ts
 *
 * site/report-tokens.test.ts fails when the committed module is out of date.
 */
import fs from 'node:fs'
import path from 'node:path'
import { buildOutputs } from '@dta/build'
import { parseTokenFiles } from '@dta/core'
import config from '../dta.config.js'

const siteDir = path.resolve(import.meta.dirname, '..')
export const REPORT_TOKENS_MODULE = path.resolve(
  siteDir,
  '..',
  'packages',
  'visual-diff',
  'src',
  'report',
  'tokens-css.ts',
)

/** Comments and blank lines out: the module only needs the declarations. */
const compact = (css: string) =>
  css
    .replace(/\/\*\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map((line) => line.trimEnd())
    .filter((line) => line.trim() !== '')
    .join('\n')

export async function reportTokensModule(): Promise<string> {
  const dir = path.join(siteDir, 'tokens')
  const files = fs
    .readdirSync(dir)
    .filter((name) => name.endsWith('.json'))
    .sort()
    .map((fileName) => ({ fileName, content: fs.readFileSync(path.join(dir, fileName), 'utf8') }))
  const { model } = parseTokenFiles(files)
  const { files: outputs } = await buildOutputs(model, { brands: config.brands })
  const pick = (name: string) => {
    const file = outputs.find((f) => f.path === `output/css/${name}`)
    if (!file) throw new Error(`dta build wrote no ${name}`)
    return compact(file.content)
  }
  const css = [pick('base.css'), ...config.brands.map((b) => pick(`themes/${b.toLowerCase()}.css`))]
  return [
    '// Generated by `pnpm report:tokens` from site/tokens (DTA Drafting Table). Do not edit.',
    '',
    '/** Token CSS of the report: primitives on :root, one theme per [data-brand]. */',
    `export const DRAFTING_TABLE_CSS = ${JSON.stringify(css.join('\n'))}`,
    '',
  ].join('\n')
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  fs.writeFileSync(REPORT_TOKENS_MODULE, await reportTokensModule())
  console.log(`Wrote ${path.relative(process.cwd(), REPORT_TOKENS_MODULE)}`)
}
