/**
 * The playground's outputs and the hand-off to the CLI (spec: docs/specs/playground.md decisions
 * 3 and 9, TICKET-079): which outputs to build, how the files are grouped, the `dta.config.ts`
 * that gives the same files with `dta build`, and the commands to run. Pure and small: it imports
 * only types from `@dta/build`, so the page's first load stays without Style Dictionary. The
 * build itself and the zip code are in outputs-engine.ts, loaded when the Outputs tab opens.
 */
import type { OutputFile, OutputFormat } from '@dta/build'

/** The outputs a visitor can choose, in the order of the config reference (`OUTPUT_FORMATS`). */
export const OUTPUT_CHOICES: ReadonlyArray<{ format: OutputFormat; label: string }> = [
  { format: 'css', label: 'CSS' },
  { format: 'tailwind-v4', label: 'Tailwind v4' },
  { format: 'tailwind-v3', label: 'Tailwind v3' },
  { format: 'js', label: 'JS' },
]

export const ALL_FORMATS: readonly OutputFormat[] = OUTPUT_CHOICES.map((choice) => choice.format)

/** The command that runs DTA without an install (the npm name `dta` is another package). */
export const CLI = 'npx design-token-authority'
export const CONFIG_FILE = 'dta.config.ts'

/** Where `dta build` writes by default; the playground keeps the defaults. */
const GROUPS = [
  { id: 'css', name: 'CSS', dir: 'output/css/' },
  { id: 'tailwind', name: 'Tailwind', dir: 'output/tailwind/' },
  { id: 'js', name: 'JS', dir: 'output/js/' },
] as const

export type OutputGroupId = (typeof GROUPS)[number]['id']

export interface OutputGroup {
  id: OutputGroupId
  name: string
  files: OutputFile[]
}

/** The files by kind (CSS, Tailwind, JS), in path order; kinds without files are left out. */
export function groupOutputs(files: readonly OutputFile[]): OutputGroup[] {
  return GROUPS.map((group) => ({
    id: group.id,
    name: group.name,
    files: files.filter((file) => file.path.startsWith(group.dir)),
  })).filter((group) => group.files.length > 0)
}

/**
 * The output a file belongs to, where its group mixes outputs (the Tailwind group holds the v4
 * `tailwind.css` and the v3 `tailwind.tokens.ts`): `Tailwind v4`, `Tailwind v3`. None where the
 * group is one output (CSS, JS), so nothing is said twice. From `OutputFile.format` (@dta/build).
 */
export function outputLabel(group: OutputGroup, file: OutputFile): string | undefined {
  const formats = new Set(group.files.map((f) => f.format))
  if (formats.size < 2 || !file.format) return undefined
  return OUTPUT_CHOICES.find((choice) => choice.format === file.format)?.label
}

/** The groups as the OutputFiles component shows them: sizes, the zip label, the output labels. */
export function outputFileGroups(groups: readonly OutputGroup[]) {
  return groups.map((group) => ({
    id: group.id,
    name: group.name,
    downloadLabel: `Download ${group.name} (.zip)`,
    files: group.files.map((file) => ({
      path: file.path,
      content: file.content,
      size: formatSize(byteLength(file.content)),
      tag: outputLabel(group, file),
    })),
  }))
}

/** UTF-8 bytes of a file's content. */
export const byteLength = (content: string) => new TextEncoder().encode(content).length

/** `746 B`, `1.2 KB` (1024 bytes to the KB, one decimal). */
export function formatSize(bytes: number): string {
  return bytes < 1024 ? `${bytes} B` : `${(bytes / 1024).toFixed(1)} KB`
}

export const plural = (count: number, word: string) => `${count} ${word}${count === 1 ? '' : 's'}`

export interface ConfigChoices {
  /** The modes built into a theme each (the brands the structure analysis suggests). */
  brands: readonly string[]
  formats: readonly OutputFormat[]
  /**
   * Import `defineConfig` from the package (editor support). Only once the package is on npm
   * (`NPM_RELEASED`): before that the import does not resolve, so the config is a plain object.
   */
  defineConfig?: boolean
}

const quoted = (values: readonly string[]) =>
  values.map((value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`).join(', ')

/**
 * The `dta.config.ts` for the choices made in the playground. `dta build` with it, on the same
 * token files in `tokens/`, writes the files the playground shows (outputs.test.ts runs the CLI).
 */
export function generateConfig({ brands, formats, defineConfig = false }: ConfigChoices): string {
  const body = [
    "  figma: { source: 'file' },",
    "  tokens: { dir: 'tokens' },",
    ...(brands.length > 0 ? [`  brands: [${quoted(brands)}],`] : []),
    '  outputs: {',
    `    formats: [${quoted(formats)}],`,
    '  },',
  ]
  return [
    `// Generated by the DTA playground. Token files go in tokens/; run: ${CLI} build`,
    ...(defineConfig
      ? [
          "import { defineConfig } from 'design-token-authority'",
          '',
          'export default defineConfig({',
        ]
      : ['export default {']),
    ...body,
    defineConfig ? '})' : '}',
    '',
  ].join('\n')
}

/** One step of "Take it to the CLI": what to do, and the command for it when there is one. */
export interface CliStep {
  text: string
  command?: string
}

/**
 * The commands that give the same files on the visitor's machine. Per-mode files go into
 * `tokens/` as they are; a plugin export is imported first, like the playground did.
 */
export function cliSteps(source: { pluginExport?: string }): CliStep[] {
  const config = `Put ${CONFIG_FILE} in your project folder.`
  if (source.pluginExport) {
    return [
      { text: config },
      {
        text: 'Import the plugin export into tokens/, as the playground did:',
        command: `${CLI} pull --from-file ${source.pluginExport}`,
      },
      { text: 'Build:', command: `${CLI} build` },
    ]
  }
  return [
    { text: `${config} Put the token files in tokens/ next to it.` },
    { text: 'Build:', command: `${CLI} build` },
  ]
}
